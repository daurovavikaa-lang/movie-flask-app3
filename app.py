@app.route("/", methods=["GET", "POST"])
def index():
    # Сортируем по рейтингу (по убыванию) для топа
    sorted_by_rating = sorted(MOVIES, key=lambda m: m["rating"], reverse=True)
    
    top_3 = sorted_by_rating[:3]
    rest = sorted_by_rating[3:]

    suggested = None
    if request.method == "POST" and request.form.get("action") == "suggest":
        suggested = random.choice(MOVIES)

    return render_template("index.html", top_3=top_3, rest=rest, suggested=suggested)

@app.route("/movie/<title>")
def movie_detail(title):
    movie = next((m for m in MOVIES if m["title"].lower() == title.lower()), None)
    if not movie:
        return "Фильм не найден", 404
    return render_template("movie.html", movie=movie)

